from __future__ import annotations

import json
import hashlib
import unittest
from pathlib import Path
from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker

import backend.app.services.db
import backend.app.services.models
import backend.app.services.storage

from datetime import UTC, datetime
from backend.app.services.crypto_local import encrypt_bytes
from backend.app.services.models import AccountArtifactModel
from backend.app.services.storage import (
    list_docs,
    list_lessons,
    add_doc,
    save_embeddings,
)


class EmbeddingsStorageTests(unittest.TestCase):
    SessionLocal = None
    memory_engine = None

    @classmethod
    def setUpClass(cls) -> None:
        # Patch database targets to use in-memory SQLite for testing
        cls.orig_db_url = backend.app.services.db.DATABASE_URL
        cls.orig_db_engine = backend.app.services.db.engine
        cls.orig_db_session = backend.app.services.db.SessionLocal
        cls.orig_storage_session = backend.app.services.storage.SessionLocal
        cls.orig_effective_url = backend.app.services.db.EFFECTIVE_DATABASE_URL

        cls.memory_engine = create_engine("sqlite:///:memory:", future=True)
        cls.SessionLocal = sessionmaker(bind=cls.memory_engine, autoflush=False, autocommit=False, future=True)

        backend.app.services.db.Base.metadata.create_all(bind=cls.memory_engine)

        backend.app.services.db.DATABASE_URL = "postgresql+psycopg://dummy:dummy@localhost/dummy"
        backend.app.services.db.EFFECTIVE_DATABASE_URL = backend.app.services.db.DATABASE_URL
        backend.app.services.db.engine = cls.memory_engine
        backend.app.services.db.SessionLocal = cls.SessionLocal
        backend.app.services.storage.SessionLocal = cls.SessionLocal

    @classmethod
    def tearDownClass(cls) -> None:
        # Restore original database settings
        backend.app.services.db.DATABASE_URL = cls.orig_db_url
        backend.app.services.db.EFFECTIVE_DATABASE_URL = cls.orig_effective_url
        backend.app.services.db.engine = cls.orig_db_engine
        backend.app.services.db.SessionLocal = cls.orig_db_session
        backend.app.services.storage.SessionLocal = cls.orig_storage_session

    def setUp(self) -> None:
        # Clear database tables before each test
        with self.SessionLocal() as db:
            db.query(backend.app.services.models.AccountArtifactModel).delete()
            db.commit()

    def test_embeddings_lifecycle_stateless(self) -> None:
        user_dek = b"v" * 32
        account_id = "test_embedder"
        doc_name = "physics.txt"
        doc_content = b"E equals MC squared."

        # 1. Add normal document
        doc = add_doc(name=doc_name, content=doc_content, account_id=account_id, user_dek=user_dek)
        self.assertEqual(doc.name, doc_name)
        self.assertEqual(len(doc.chunks), 1)
        chunk_id = doc.chunks[0].chunk_id

        # 2. Verify listing matches 1 document (no embeddings companion listed as document)
        docs = list_docs(account_id=account_id, user_dek=user_dek)
        self.assertEqual(len(docs), 1)
        self.assertEqual(docs[0].id, doc.id)
        self.assertIsNone(docs[0].chunks[0].vector)

        # 3. Save mock embeddings generated by client
        mock_embeddings = {
            "chunks": [
                {
                    "chunk_id": chunk_id,
                    "text": "E equals MC squared.",
                    "vector": [0.1] * 384
                }
            ]
        }
        save_embeddings(
            doc_id=doc.id,
            embeddings_data=mock_embeddings,
            account_id=account_id,
            user_dek=user_dek
        )

        # 4. Check database row exists for physics.txt.embeddings.json
        from backend.app.services.models import AccountArtifactModel
        with self.SessionLocal() as db:
            embed_row = db.query(AccountArtifactModel).where(
                AccountArtifactModel.account_id == account_id,
                AccountArtifactModel.relative_path == f"documents/{doc_name}.embeddings.json"
            ).first()
            self.assertIsNotNone(embed_row)

        # 5. Reload document listing and check if vector is dynamically attached to chunk
        docs = list_docs(account_id=account_id, user_dek=user_dek)
        self.assertEqual(len(docs), 1) # Companion file must be filtered/ignored!
        self.assertIsNotNone(docs[0].chunks[0].vector)
        self.assertEqual(docs[0].chunks[0].vector, [0.1] * 384)

    def test_curriculum_lessons_load_from_encrypted_stateless_artifact(self) -> None:
        user_dek = b"q" * 32
        account_id = "test_lessons"
        payload = {
            "curriculum": {
                "topics": [
                    {
                        "id": "topic_graphs",
                        "title": "Graphs",
                        "summary": "Understand graph traversal.",
                    }
                ]
            }
        }
        content = json.dumps(payload).encode("utf-8")

        with self.SessionLocal() as db:
            db.add(
                AccountArtifactModel(
                    account_id=account_id,
                    relative_path="output/output_curriculum_qa.json",
                    content=encrypt_bytes(user_dek, content),
                    sha256=hashlib.sha256(content).hexdigest(),
                    size_bytes=len(content),
                    updated_at=datetime.now(UTC),
                )
            )
            db.commit()

        self.assertEqual(list_lessons(account_id=account_id), [])
        lessons = list_lessons(account_id=account_id, user_dek=user_dek)

        self.assertEqual(len(lessons), 1)
        self.assertEqual(lessons[0].id, "topic_graphs")
        self.assertEqual(lessons[0].title, "Graphs")
        self.assertEqual(lessons[0].objective, "Understand graph traversal.")


if __name__ == "__main__":
    unittest.main()
